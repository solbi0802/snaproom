import { expect, test } from '@playwright/test'

test('keyboard focus follows the editor and export steps', async ({ page, isMobile }) => {
  if (isMobile) await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: '본문으로 이동' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()

  await page.getByRole('button', { name: '샘플 일러스트로 둘러보기' }).press('Enter')
  const start = page.getByRole('button', { name: '사진 배치 시작' })
  await start.press('Enter')
  const heading = page.getByRole('heading', { name: '사진 배치', exact: true })
  await expect(heading).toBeFocused()
  const canvas = page.getByRole('img', { name: '사진 배치 미리보기' })
  await expect(canvas).toBeVisible()

  const gap = page.getByRole('slider', { name: '사진 여백' })
  await gap.press('End')
  await expect(gap).toHaveValue('64')
  await page.getByRole('spinbutton', { name: '배경색 R' }).focus()
  await page.keyboard.press('Control+z')
  await expect(gap).toHaveValue('64')
  await heading.focus()
  await page.keyboard.press('Control+z')
  await expect(gap).toHaveValue('12')
  await expect(page.getByRole('status')).toHaveText('마지막 편집을 되돌렸어요.')

  await page.getByRole('button', { name: '스티커', exact: true }).press('Enter')
  await page.getByRole('button', { name: '별 추가' }).press('Enter')
  const sticker = page.getByRole('button', { name: '1. 별 스티커' })
  await expect(sticker).toBeFocused()
  const left = () => sticker.evaluate(element => parseFloat(element.style.left))
  const before = await left()
  await page.keyboard.press('ArrowRight')
  await expect.poll(left).toBeCloseTo(before + 1)

  if (isMobile) {
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  }
  await page.getByRole('button', { name: '저장 미리보기' }).press('Enter')
  await expect(page.getByRole('heading', { name: '저장 미리보기' })).toBeFocused()
  await page.getByRole('button', { name: '배치로 돌아가기' }).press('Enter')
  await expect(heading).toBeFocused()
  await page.getByRole('button', { name: '사진 선택으로 돌아가기' }).press('Enter')
  await expect(start).toBeFocused()
  await page.getByRole('button', { name: '캔버스 가방 제거' }).press('Enter')
  await expect(page.getByRole('heading', { name: '선택한 사진' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '모두 비우기' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: '사진 선택하기' })).toBeFocused()
})
